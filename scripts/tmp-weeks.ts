import { readFileSync } from "node:fs";
import { buildModel, leagueStrength } from "../shared/strength.ts";
import { leagueProfiles } from "../shared/teamProfile.ts";
import { weekScores } from "../shared/weekScores.ts";
import { RECORDED_WEEKS } from "../server/recordedWeeks.ts";
const snapshot = JSON.parse(readFileSync("/tmp/real/league.json", "utf8"));
const report = JSON.parse(readFileSync("/tmp/real/stats.json", "utf8"));
const model = buildModel(snapshot, report);
const strengths = leagueStrength(snapshot, model);
const history = weekScores({ marks: {} }, RECORDED_WEEKS[snapshot.league.id]!, 4);
const profiles = leagueProfiles(snapshot, model, strengths, report.players, { history });
const goat = profiles.get(7)!;
const mean = (x: number[]) => x.reduce((a, b) => a + b, 0) / x.length;
const ahead = goat.weeks.filter((w) => !w.final), past = goat.weeks.filter((w) => w.final);
console.log("past avg/high/low", mean(past.map((w) => w.leagueAverage)).toFixed(1), mean(past.map((w) => w.leagueHigh)).toFixed(1), mean(past.map((w) => w.leagueLow)).toFixed(1));
console.log("ahead avg/high/low", mean(ahead.map((w) => w.leagueAverage)).toFixed(1), mean(ahead.map((w) => w.leagueHigh)).toFixed(1), mean(ahead.map((w) => w.leagueLow)).toFixed(1));
console.log("goat", goat.ahead, "rate", goat.rate, "strength", strengths.find((s) => s.rosterId === 7)!.projected.toFixed(2));
console.log(ahead.slice(0, 6).map((w) => `${w.week}: ${w.team.toFixed(0)} avg ${w.leagueAverage.toFixed(0)} [${w.leagueLow.toFixed(0)}-${w.leagueHigh.toFixed(0)}]`).join(" | "));
for (const k of ["ceiling", "floor"]) console.log(k, [...profiles.values()].map((p) => p.shape.find((a) => a.key === k)!).map((a) => `${a.value.toFixed(0)}#${a.rank}`).join(" "));
