import { readFileSync } from "node:fs";
import { rosterPlayers } from "../shared/analysis.ts";
import { buildModel, fillRoster, leagueStrength, weeklyTotals } from "../shared/strength.ts";
import { RECORDED_WEEKS } from "../server/recordedWeeks.ts";
const snapshot = JSON.parse(readFileSync("/tmp/real/league.json", "utf8"));
const report = JSON.parse(readFileSync("/tmp/real/stats.json", "utf8"));
const model = buildModel(snapshot, report);
const rec = RECORDED_WEEKS[snapshot.league.id]!;
const rows = snapshot.teams.map((team: any) => {
  const ids = rosterPlayers(team).map((p: any) => p.id);
  const totals = weeklyTotals(model, fillRoster(model, ids).ids);
  const mean = totals.reduce((a, b) => a + b, 0) / totals.length;
  const sd = Math.sqrt(totals.reduce((a, b) => a + (b - mean) ** 2, 0) / totals.length);
  const actual = rec.map((w) => w.points[team.rosterId]!);
  const am = actual.reduce((a, b) => a + b, 0) / actual.length;
  const asd = Math.sqrt(actual.reduce((a, b) => a + (b - am) ** 2, 0) / actual.length);
  const players = ids.flatMap((id: string) => model.players.get(id) ?? []).sort((a: any, b: any) => b.average - a.average);
  const top9avg = players.slice(0, 9).reduce((s: number, p: any) => s + p.average, 0);
  const top9proj = players.slice(0, 9).reduce((s: number, p: any) => s + p.projected, 0);
  return { team: team.teamName.slice(0, 14), model: +mean.toFixed(1), modelSd: +sd.toFixed(1), actual: +am.toFixed(1), actualSd: +asd.toFixed(1), top9avg: +top9avg.toFixed(1), top9proj: +top9proj.toFixed(1) };
});
console.table(rows);
const m = rows.map((r: any) => r.model), a = rows.map((r: any) => r.actual);
const mean = (x: number[]) => x.reduce((s, v) => s + v, 0) / x.length;
const mm = mean(m), am = mean(a);
const corr = m.reduce((s: number, v: number, i: number) => s + (v - mm) * (a[i]! - am), 0) / Math.sqrt(m.reduce((s: number, v: number) => s + (v - mm) ** 2, 0) * a.reduce((s: number, v: number) => s + (v - am) ** 2, 0));
console.log("league model", mm.toFixed(1), "actual", am.toFixed(1), "ratio", (am / mm).toFixed(3), "corr", corr.toFixed(2));
console.log("weeks", model.weeks, "calendar", model.calendar.weeks.length, "MAX games?");
